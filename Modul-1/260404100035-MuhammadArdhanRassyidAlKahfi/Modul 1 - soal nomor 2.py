# INPUT
r = float(input("Masukkan jari-jari alas kerucut (cm): "))
t = input("Masukkan tinggi kerucut (cm): ")
pi = 3.14159265358979

# HITUNG
volume = (1 / 3) * pi * (r ** 2) * t

# OUTPUT
print("HASIL PERHITUNGAN")
print("Jari jari alas :", r, "cm")
print("Tinggi kerucut :", t, "cm")
print("Volume kerucut :", volume, "cm^3")



