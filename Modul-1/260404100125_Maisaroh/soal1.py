saldoUdin = 100000 * 2
totalbuku = 3 * 25000
print("Total Harga Buku = " + str(totalbuku))
totalpulpen = 2 * 8000
print("Total Harga Pulpen = " + str(totalpulpen))
totalflashdisk = 1 * 75000
print("Total Harga Flashdisk = " + str(totalflashdisk))
totalbelanja = totalbuku + totalpulpen + totalflashdisk
print("Total Belanja = " + str(totalbelanja))
diskon = float(totalbelanja * 10) / 100
print("Hasil Diskon = " + str(diskon))
setelahdiskon = totalbelanja - diskon
print("Hasil Setelah Diskon = " + str(setelahdiskon))
ppn = float(setelahdiskon * 11) / 100
print("Hasil PPN = " + str(ppn))
totalbayar = setelahdiskon + ppn
print("Total Semua yang Dibayar = " + str(totalbayar))
kembalian = saldoUdin - totalbayar
print("Uang yang Dikembalikan = " + str(kembalian))
